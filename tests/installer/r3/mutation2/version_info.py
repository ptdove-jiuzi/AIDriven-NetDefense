"""The Windows version resource stamped into Setup.exe.

Everything Windows shows about the binary comes from here:

* ``CompanyName``    — ``PT-dove`` (the only author string allowed in any artefact),
* ``ProductName``    — ``AIDriven NetDefense``,
* ``FileDescription``— one line, both languages: what the user reads in the UAC
  prompt, in Explorer's Details pane and in SmartScreen's "unrecognised app" dialog.

``FileVersion`` / ``ProductVersion`` carry the release version as four integers, because
the resource is a fixed-point field; the human-readable string with a prerelease suffix
(``0.0.1-rc.1``) goes in ``StringFileInfo``.  Both are derived from the same input, so
they cannot disagree.

Author: PT-dove
"""

from __future__ import annotations

import re

PRODUCT_NAME = "AIDriven NetDefense"
PRODUCT_NAME_ZH = "网域智防"
COMPANY = "PT-dove"

#: Used as ``OriginalFilename``; the build overrides the whole name with the real one.
DEFAULT_INTERNAL_NAME = "AIDrivenNetDefense-Setup"


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """``0.0.1-rc.1`` → ``(0, 0, 1, 0)``.

    The resource cannot hold a prerelease marker, so the fourth component stays 0 for
    ``rc`` builds; the string block is what distinguishes them.  A version that does
    not start with a number is a build error, not something to guess at.
    """

    numbers = re.findall(r"\d+", version.split("-", 1)[0])
    if not numbers:
        raise ValueError(f"version has no numeric component: {version!r}")
    parts = [int(value) for value in numbers[:4]]
    while len(parts) < 4:
        parts.append(0)
    if any(part > 65535 for part in parts):
        raise ValueError(f"version component out of range: {version!r}")
    return tuple(parts)  # type: ignore[return-value]


def description(version: str) -> str:
    """One bilingual line, no newline: the field is single-line by definition."""

    return f"{PRODUCT_NAME} {version} 安装程序 / Setup (unofficial build, unsigned)"


def render(version: str, internal_name: str = DEFAULT_INTERNAL_NAME) -> str:
    """Text of the PyInstaller ``--version-file``."""

    a, b, c, d = version_tuple(version)
    file_version = f"{a}.{b}.{c}.{d}"
    return f"""# UTF-8
# Version resource for {internal_name} ({version}).
# Generated by deploy/windows/installer/app/build_setup.py — do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({a}, {b}, {c}, {d}),
    prodvers=({a}, {b}, {c}, {d}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [StringStruct('CompanyName', '{COMPANY}'),
           StringStruct('FileDescription', '{description(version)}'),
           StringStruct('FileVersion', '{file_version}'),
           StringStruct('InternalName', '{internal_name}'),
           StringStruct('LegalCopyright', 'Copyright (c) {COMPANY}'),
           StringStruct('OriginalFilename', '{internal_name}.exe'),
           StringStruct('ProductName', '{PRODUCT_NAME}'),
           StringStruct('ProductVersion', '{version}')])
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
