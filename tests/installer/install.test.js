/**
 * End-to-end install drill, in disarm mode.
 *
 * "End-to-end" here means the real engine, the real state machine, the real hash gate and
 * the real plan writer — everything except the privileged syscalls, which are recorded
 * instead of executed. That is the only honest way to run this on a workstation: a test
 * suite that creates a Windows service to prove it can create a Windows service leaves
 * the machine changed when it fails.
 */

import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import { runInstall } from '../../deploy/windows/installer/src/install.mjs';
import { loadJournal } from '../../deploy/windows/installer/src/journal.mjs';
import { SERVICE_NAME } from '../../deploy/windows/installer/src/paths.mjs';
import { createPayload, disarmContext, readPlan, tempRoot } from './fixtures/payload.mjs';

// `fileURLToPath`, not `URL.pathname`: the repository path contains non-ASCII characters,
// which pathname would hand back percent-encoded.
const INSTALLER_SOURCE = fileURLToPath(new URL('../../deploy/windows/installer/', import.meta.url));

function readJsonFile(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Install once with the fixture payload and return everything a test wants to assert on. */
async function installOnce(t, { version = '0.0.1', payloadOptions = {}, installOptions = {} } = {}) {
  const root = tempRoot(t);
  const payload = createPayload(join(root, 'payload'), { version, ...payloadOptions });
  const { layout, logger, ops } = disarmContext(join(root, 'install-root'), { version });
  const result = await runInstall({
    layout,
    options: {
      payload: payload.root,
      toVersion: version,
      engineSource: INSTALLER_SOURCE,
      ...installOptions,
    },
    logger,
    ops,
  });
  return { root, payload, layout, logger, ops, result };
}

test('a full disarm install completes and writes every documented artifact', async (t) => {
  const { payload, layout, result } = await installOnce(t);
  assert.equal(result.code, 0, result.message);

  // Payload landed and the manifest is byte-identical to the source manifest.
  const installedManifest = join(layout.appRoot, 'manifests', 'files.sha256');
  assert.ok(existsSync(installedManifest), 'app/manifests/files.sha256 missing');
  assert.deepEqual(readFileSync(installedManifest), readFileSync(payload.manifestPath));
  assert.ok(existsSync(join(layout.appRoot, 'apps/daemon/bin.js')));

  // install.json receipt.
  const receipt = readJsonFile(layout.installReceiptPath);
  assert.equal(receipt.version, '0.0.1');
  assert.equal(receipt.op, 'install');
  assert.equal(receipt.programRoot, layout.programRoot);
  assert.equal(receipt.dataRoot, layout.dataRoot);
  assert.equal(receipt.fileCount, payload.fileCount);
  assert.equal(receipt.manifestDigest, payload.digest);
  assert.equal(receipt.apiPort, 8787);
  assert.equal(receipt.author, 'PT-dove');

  // Machine-local path registration used by uninstall.
  const registration = readJsonFile(layout.uninstallRegistryPath);
  assert.equal(registration.registryKeys.length, 3);
  assert.equal(registration.startMenuDir, layout.startMenuDir);

  // Journal reached a terminal state and kept the whole history.
  const journal = loadJournal(layout.journalPath);
  assert.equal(journal.state, 'ok');
  assert.equal(journal.journal.phase, 'COMMITTED');
  const phases = journal.journal.data.steps.map((step) => step.phase);
  for (const phase of ['STAGED', 'SWAP_B', 'COMMITTED']) {
    assert.ok(phases.includes(phase), `journal is missing ${phase}`);
  }

  // Token: generated by the installer, inside the daemon's grammar, and only summarised in the log.
  const token = readFileSync(layout.tokenPath, 'utf8').trim();
  assert.match(token, /^[A-Za-z0-9_-]{32,512}$/u);
  assert.equal(token.length, 43);

  // Config: explicit dataDir, explicit rule pack inside dataDir, fixed loopback port.
  const config = readJsonFile(layout.configPath);
  assert.equal(config.dataDir, layout.dataDir);
  assert.equal(config.mode, 'full');
  assert.equal(config.api.host, '127.0.0.1');
  assert.equal(config.api.port, 8787);
  assert.equal(config.api.tokenFile, 'secrets/api-token');
  assert.equal(config.detection.rulePackPath, 'rules/pack.json');
  assert.ok(existsSync(join(layout.dataDir, 'rules', 'pack.json')), 'rule pack not copied into dataDir');

  // Floor was written from the installed version.
  assert.equal(readJsonFile(layout.versionFloorPath).hardFloorMax, '0.0.1');

  // Engine copy for the ARP uninstall entry.
  assert.ok(existsSync(layout.enginePath), 'engine copy missing');

  // Staging is gone: a leftover staging tree is what makes a later run think it can resume.
  assert.equal(existsSync(layout.stagingRoot), false);
});

test('the plan records ACLs, service registration, registry entries and the Start menu item', async (t) => {
  const { layout, result } = await installOnce(t);
  assert.equal(result.code, 0, result.message);

  const plan = readPlan(layout);
  const ops = plan.map((entry) => entry.op);

  // ACLs come first: the service account must not be able to read a file before its
  // parent directory is protected.
  assert.ok(ops.indexOf('acl.apply') < ops.indexOf('service.install'), 'ACLs must precede service registration');
  assert.equal(ops.filter((op) => op === 'acl.apply').length, 7);

  const secretsAcl = plan.find((entry) => entry.op === 'acl.apply' && entry.path === layout.secretsDir);
  assert.equal(secretsAcl.protected, true, 'data\\secrets must stop inheriting');

  const serviceInstall = plan.find((entry) => entry.op === 'service.install');
  assert.ok(serviceInstall.argv.includes('--install-service'));
  assert.ok(serviceInstall.argv.includes(`NT SERVICE\\${SERVICE_NAME}`), 'must not use LocalSystem');

  // `--preshutdown-ms` is the same shape as the H4 flag: the host does not parse it, and the
  // value only "arrives" because the C++ default happens to be the same number. So assert both
  // halves — what we ask for, and that the host's built-in default is still that number. If
  // either drifts, this goes red instead of quietly succeeding for the wrong reason.
  assert.ok(serviceInstall.argv.includes('--preshutdown-ms'));
  assert.ok(serviceInstall.argv.includes('120000'));
  const nativeHost = readFileSync(
    fileURLToPath(new URL('../../apps/service-host/native/aegis-svc.cpp', import.meta.url)),
    'utf8',
  );
  assert.match(nativeHost, /kPreshutdownMs\s*=\s*120000/u,
    'the requested preshutdown timeout must equal the host default while the flag is unparsed');

  // H4: the plan must not claim the host does something it does not implement. The old
  // assertion here was `argv.includes('--event-log-readers')` — true by construction, because
  // the installer always put the flag in the argv, while `aegis-svc.exe` never parsed it and
  // no `S-1-5-32-573` membership was ever created. The membership is now an installer action
  // with a real inverse, so *that* is what gets asserted; the dead flag is gone.
  assert.equal(serviceInstall.argv.includes('--event-log-readers'), false,
    'a flag the host does not parse is evidence of nothing — it must not be recorded as if it were');

  const readersAdd = plan.find((entry) => entry.op === 'eventlog.readers.add');
  assert.ok(readersAdd, 'the service account must be added to Event Log Readers (ADR D14)');
  assert.equal(readersAdd.sid, 'S-1-5-32-573');
  assert.equal(readersAdd.account, `NT SERVICE\\${SERVICE_NAME}`);
  assert.ok(
    ops.indexOf('eventlog.readers.add') > ops.indexOf('service.install'),
    'the virtual account only exists after the service is created',
  );
  assert.ok(
    ops.indexOf('eventlog.readers.add') < ops.indexOf('service.start'),
    'the membership must exist before the service reads the Security log',
  );

  // The service must never be created by sc.exe (ADR §3.2: error 1053, no virtual account),
  // and nothing but install+start may touch it during an install.
  assert.deepEqual(ops.filter((op) => op.startsWith('service.')), ['service.install', 'service.start']);
  assert.equal(plan.some((entry) => /sc\.exe/u.test(JSON.stringify(entry))), false);

  const arpDisplay = plan.find((entry) => entry.op === 'registry.set' && entry.name === 'DisplayName');
  assert.match(arpDisplay.value, /AIDriven NetDefense/u);
  assert.match(arpDisplay.value, /0\.0\.1/u);
  assert.match(arpDisplay.key, /Uninstall\\\{9C3D5F86/u);

  const uninstallString = plan.find((entry) => entry.op === 'registry.set' && entry.name === 'UninstallString');
  assert.match(uninstallString.value, /\/uninstall \/silent/u);
  assert.match(uninstallString.value, /install\\engine\\main\.mjs/u);

  const shortcut = plan.find((entry) => entry.op === 'shortcut.create');
  assert.equal(shortcut.lnk, layout.startMenuShortcut);
  assert.equal(shortcut.target, layout.cliStub);
});

test('a same-version install is a repair: data and token are untouched, swap path is used', async (t) => {
  const root = tempRoot(t);
  const payload = createPayload(join(root, 'payload'));
  const { layout, logger, ops } = disarmContext(join(root, 'install-root'));

  const first = await runInstall({
    layout, options: { payload: payload.root, toVersion: '0.0.1', engineSource: INSTALLER_SOURCE }, logger, ops,
  });
  assert.equal(first.code, 0, first.message);
  const tokenBefore = readFileSync(layout.tokenPath, 'utf8');
  const configBefore = readFileSync(layout.configPath, 'utf8');

  // A file the daemon would own. Nothing in the installer is allowed to delete it.
  mkdirSync(layout.storeDir, { recursive: true });
  writeFileSync(layout.storePath, 'user data that must survive a repair\n');

  const second = await runInstall({
    layout, options: { payload: payload.root, toVersion: '0.0.1', engineSource: INSTALLER_SOURCE }, logger, ops,
  });
  assert.equal(second.code, 0, second.message);

  assert.equal(readFileSync(layout.tokenPath, 'utf8'), tokenBefore, 'repair must not rotate the token');
  assert.equal(readFileSync(layout.configPath, 'utf8'), configBefore, 'repair must not rewrite user configuration');
  assert.equal(readFileSync(layout.storePath, 'utf8'), 'user data that must survive a repair\n');

  const journal = loadJournal(layout.journalPath);
  assert.equal(journal.journal.data.op, 'repair');
  assert.ok(journal.journal.data.steps.some((step) => step.phase === 'SWAP_A'), 'repair must go through app.prev');
});

test('three installs in a row converge (§6.2 combination 4 is handled, not tripped)', async (t) => {
  const root = tempRoot(t);
  const payload = createPayload(join(root, 'payload'));
  const { layout, logger, ops } = disarmContext(join(root, 'install-root'));

  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const result = await runInstall({
      layout, options: { payload: payload.root, toVersion: '0.0.1', engineSource: INSTALLER_SOURCE }, logger, ops,
    });
    assert.equal(result.code, 0, `attempt ${attempt}: ${result.message}`);
  }
  const manifest = readFileSync(join(layout.appRoot, 'manifests', 'files.sha256'));
  assert.deepEqual(manifest, readFileSync(payload.manifestPath));
});

/**
 * A non-terminal phase that has **no implemented convergence** in this slice.
 *
 * This used to be `SWAP_B`, which was the right fixture only while no recovery existed: with
 * `recovery.mjs` in place, a `SWAP_B` journal over a tree whose manifest equals
 * `toManifestDigest` is provably the "rename landed, settle did not" state, and /install now
 * converges it and answers 26 (see `regressions.test.js`). To keep testing "refuses and
 * writes nothing", the phase has to be one §6.2 describes but this slice cannot recover:
 * the migration phases belong to the upgrade path, which is out of scope (G2).
 */
test('an in-flight journal that cannot be converged refuses a new install with 15', async (t) => {
  const { layout, logger, ops, root } = await installOnce(t);
  const journal = readJsonFile(layout.journalPath);
  journal.phase = 'MIGRATING';
  writeFileSync(layout.journalPath, JSON.stringify(journal));
  const receiptBefore = readFileSync(layout.installReceiptPath, 'utf8');

  const payload = createPayload(join(root, 'payload2'));
  const result = await runInstall({
    layout, options: { payload: payload.root, toVersion: '0.0.1', engineSource: INSTALLER_SOURCE }, logger, ops,
  });
  assert.equal(result.code, 15);
  assert.match(result.message, /进行中事务/u);

  // Nothing was installed over the top, and the receipt is untouched.
  assert.equal(readFileSync(layout.installReceiptPath, 'utf8'), receiptBefore);
  assert.equal(existsSync(layout.stagingRoot), false, 'a refused install must not start staging');
});

