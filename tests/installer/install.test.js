test('an upgrade is refused explicitly instead of being attempted', async (t) => {
  const { layout, logger, ops, root } = await installOnce(t);
  const nextPayload = createPayload(join(root, 'payload-next'), { version: '0.0.2' });

  const result = await runInstall({
    layout, options: { payload: nextPayload.root, toVersion: '0.0.2', engineSource: INSTALLER_SOURCE }, logger, ops,
  });
  assert.equal(result.code, 10);
  assert.match(result.message, /升级路径未在本切片实现/u);
  // The old install is still intact and still the old version.
  assert.equal(readJsonFile(layout.installReceiptPath).version, '0.0.1');
});

test('the generated config is accepted by the daemon validator', async (t) => {
  const { layout, result } = await installOnce(t);
  assert.equal(result.code, 0, result.message);

  const { pathToFileURL } = await import('node:url');
  const configModule = await import(pathToFileURL(join(process.cwd(), 'apps/daemon/src/config.js')).href);
  const loaded = configModule.loadConfig(readJsonFile(layout.configPath));
  assert.equal(loaded.dataDir, layout.dataDir);
  assert.equal(loaded.api.port, 8787);
  assert.equal(loaded.detection.rulePackPath, join(layout.dataDir, 'rules', 'pack.json'));
});
